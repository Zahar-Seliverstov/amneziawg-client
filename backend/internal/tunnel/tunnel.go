// Package tunnel — граница между протоколами VPN и остальной программой.
//
// Программа делится на две части, которые ничего не знают друг о друге:
//
//   - протокол и ядро (AmneziaWG на amneziawg-go, а завтра что угодно ещё)
//     умеют разобрать свой формат конфигурации и поднять по нему интерфейс;
//   - всё остальное — маршруты, DNS, правила, переподключение, API —
//     работает с поднятым интерфейсом и сводкой Spec, не заглядывая внутрь.
//
// Чтобы добавить протокол, достаточно реализовать Protocol (разбор) и Engine
// (запуск) и зарегистрировать их в Registry при старте службы. Ни менеджер
// соединения, ни API, ни интерфейс при этом не меняются.
package tunnel

import (
	"errors"
	"time"
)

// Spec — всё, что системе нужно знать о туннеле, независимо от протокола.
//
// Значения уже проверены протоколом при разборе: адреса и префиксы
// корректны, порты на месте. Потребители Spec доверяют им без повторной
// проверки.
type Spec struct {
	// Addresses — адреса интерфейса с маской ("10.8.0.2/32").
	Addresses []string
	// DNS — серверы имён, которые предлагает конфигурация.
	DNS []string
	// MTU интерфейса; 0 — на усмотрение ядра.
	MTU int
	// Endpoints — серверы ("host:port"). Путь к ним обязан идти мимо
	// туннеля, иначе зашифрованный трафик уйдёт в петлю.
	Endpoints []string
	// AllowedIPs — какой трафик туннель способен нести.
	AllowedIPs []string
	// SelfStarting — ядро начнёт обмен с сервером само, без пользовательского
	// трафика (у WireGuard — PersistentKeepalive). Иначе рукопожатие
	// начнётся, только когда маршруты поведут трафик в туннель.
	SelfStarting bool
}

// Config — разобранная конфигурация одного протокола.
//
// Конкретный тип известен только самому протоколу и ядрам, которые его
// поддерживают; остальная программа видит лишь Spec.
type Config interface {
	// Protocol — идентификатор протокола, разобравшего конфигурацию.
	Protocol() string
	// Spec — сводка для системного слоя.
	Spec() Spec
}

// Protocol разбирает текст конфигурации своего формата.
type Protocol interface {
	// ID — постоянный идентификатор; хранится рядом с конфигурацией.
	ID() string
	// Title — название для людей.
	Title() string
	// Sniff сообщает, похож ли текст на конфигурацию этого протокола.
	// Ошибаться в сторону «да» можно: окончательное слово за Parse.
	Sniff(raw string) bool
	// Parse разбирает и проверяет конфигурацию целиком. Ошибка должна
	// объяснять пользователю, что исправить.
	Parse(raw string) (Config, error)
}

// Engine поднимает интерфейс по профилю — это «ядро» протокола.
type Engine interface {
	// ID — идентификатор ядра, для журнала.
	ID() string
	// Supports сообщает, умеет ли ядро работать с этим профилем.
	Supports(Config) bool
	// Start создаёт интерфейс и запускает туннель. Адреса и маршруты
	// назначает не ядро, а системный слой — по Spec.
	//
	// Отказ из-за самих параметров (а не сети) оборачивается в
	// ErrRejected: повторять такую попытку бессмысленно.
	Start(Config, Options) (Device, error)
}

// Options — то, что системный слой задаёт ядру.
type Options struct {
	// Interface — желаемое имя интерфейса. Ядро вправе выдать другое, см.
	// Device.Name.
	Interface string
	// FirewallMark — метка на собственных пакетах туннеля, по которой
	// маршрутизация по политикам выпускает их мимо туннеля; 0 — без метки.
	FirewallMark uint32
	// Logf — журнал ядра.
	Logf func(format string, args ...any)
}

// Device — запущенный туннель.
type Device interface {
	// Name — настоящее имя интерфейса.
	Name() string
	// Stats — текущие счётчики.
	Stats() (Stats, error)
	// Done закрывается, когда ядро прекратило работу само.
	Done() <-chan struct{}
	// Close останавливает туннель и удаляет интерфейс.
	Close() error
}

// Stats — счётчики туннеля, просуммированные по всем серверам.
type Stats struct {
	RxBytes uint64
	TxBytes uint64
	// LastHandshake — последний подтверждённый обмен с сервером; нулевое
	// значение — обмена ещё не было.
	LastHandshake time.Time
}

// ErrRejected — ядро отвергло параметры конфигурации.
var ErrRejected = errors.New("ядро отвергло конфигурацию")
