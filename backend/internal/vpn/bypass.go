package vpn

// Вывод адресов мимо туннеля.
//
// «Мимо туннеля» — это не «через шлюз по умолчанию». Адрес может быть доступен
// совсем другим путём: за вторым VPN, в соседней подсети, на мосту docker. У
// такого адреса в таблице уже есть свой маршрут, и он специфичнее наших
// /1-маршрутов в туннель, то есть выигрывает и без нашей помощи.
//
// Раньше клиент этого не различал: на каждое исключение он ставил маршрут
// через шлюз по умолчанию. Для адреса, доступного иначе, это подмена
// настоящего пути на заведомо неверный — трафик уходил домашнему роутеру,
// который о такой сети ничего не знает. Со стороны выглядело хуже некуда:
// сайт, выведенный из туннеля правилом «напрямую», переставал открываться
// именно из-за этого правила.
//
// Поэтому путь не угадывается, а спрашивается у ядра: только оно знает про
// чужие интерфейсы и про то, какой маршрут сейчас выигрывает.

import (
	"log"
	"strings"

	"github.com/user/amnezia-web-client/internal/iproute"
)

// bypassRoute подбирает маршрут, выводящий префикс мимо туннеля.
//
// Второе значение — нужно ли вообще что-то ставить: путь мимо туннеля может
// уже существовать, и тогда самое верное действие — не трогать его.
func (m *Manager) bypassRoute(prefix string) (args []string, needed bool, err error) {
	path, err := m.ip.PathTo(iproute.Host(prefix))
	if err != nil {
		return nil, false, err
	}

	// Адрес самой машины. Локальная таблица маршрутизации просматривается
	// раньше всех прочих, туннель до такого адреса не доберётся, и ставить
	// нечего. Сюда попадают ответы вроде 127.0.0.1 от блокирующих серверов
	// имён — на них клиент раньше заводил бессмысленный маршрут через шлюз.
	if path.Local {
		return nil, false, nil
	}

	// Путь ведёт не в туннель — значит у адреса есть свой маршрут, и он
	// специфичнее наших /1. Оставляем как есть: это и есть «напрямую».
	if path.Device != m.ifname() {
		return nil, false, nil
	}

	// Своего маршрута у адреса нет, его забрал туннель. Значит «мимо
	// туннеля» означает «туда же, куда уходил бы весь остальной трафик».
	def, err := m.ip.DefaultPathFor(prefix)
	if err != nil {
		return nil, false, err
	}
	return def.RouteArgs(prefix), true, nil
}

// addBypassRoute выводит префикс мимо туннеля и запоминает маршрут, если его
// пришлось поставить. Вызывать под routeMu.
func (m *Manager) addBypassRoute(prefix string) error {
	args, needed, err := m.bypassRoute(prefix)
	if err != nil {
		return err
	}

	if !needed {
		log.Printf("Исключение %s и так идёт мимо туннеля — маршрут не нужен", prefix)
		return nil
	}

	return m.addRoute(args...)
}

// pinnedOutsideTunnel сообщает, есть ли у префикса собственный маршрут и ведёт
// ли он мимо туннеля.
//
// Собственный маршрут важен сам по себе: он точнее наших /1-маршрутов и
// потому переживёт их появление. Маршрут в сам туннель таким свойством не
// обладает — его как раз и нельзя считать выводом наружу.
func (m *Manager) pinnedOutsideTunnel(prefix string) bool {
	routes, err := m.ip.RoutesFor(prefix)
	if err != nil || len(routes) == 0 {
		return false
	}

	dev := "dev " + m.ifname()
	for _, route := range routes {
		if strings.Contains(route, dev) {
			return false
		}
	}
	return true
}
